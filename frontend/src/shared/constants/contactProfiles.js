function buildFallbackProfile(displayName, key) {
  const slug = key || slugPeerId(displayName) || "contact";
  const hash = hashString(slug);
  const prefix = PHONE_PREFIXES[hash % PHONE_PREFIXES.length];
  const phoneTail = String(1000000 + (hash % 8999999)).slice(0, 7);
  const emailSlug = slug.replace(/-/g, "");
  const month = (hash % 12) + 1;
  const day = (hash % 27) + 1;
  const year = 1988 + (hash % 10);

  return {
    name: displayName || "Contact",
    seed: displayName || slug,
    phone: `${prefix} ${phoneTail.slice(0, 3)} ${phoneTail.slice(3, 6)} ${phoneTail.slice(6)}`,
    email: `${emailSlug}@gmail.com`,
    position: POSITION_POOL[hash % POSITION_POOL.length],
    education: EDUCATION_POOL[hash % EDUCATION_POOL.length],
    birth: `${day} ${["January", "February", "March", "April", "May", "June", "July", "August", "September", "October", "November", "December"][month - 1]} ${year}`,
    web: `www.${emailSlug}.com`,
  };
}

export function getContactProfile(peerOrId, options = {}) {
  const displayName = String(options.name || peerOrId || "").trim();
  const key = resolveContactKey(peerOrId || displayName);
  const profile = key ? CONTACT_PROFILES[key] : null;

  if (profile) {
    return {
      ...profile,
      name: displayName || profile.name,
      seed: options.seed || profile.seed || profile.name,
      avatar: options.avatar || profile.avatar || null,
    };
  }

  return {
    ...buildFallbackProfile(displayName || "Contact", key),
    seed: options.seed || displayName || key || "Contact",
    avatar: options.avatar || null,
  };
}

export function getContactAvatarUrl(profile, peerFallback = "user") {
  if (profile?.avatar) return profile.avatar;
  const seed = encodeURIComponent(profile?.seed || profile?.name || peerFallback);
  return `https://api.dicebear.com/7.x/avataaars/svg?seed=${seed}`;
}
