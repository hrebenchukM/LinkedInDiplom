function slugPeerId(value) {
  return String(value || "")
    .trim()
    .toLowerCase()
    .replace(/^@+/, "")
    .replace(/\s+/g, "-")
    .replace(/[^a-z0-9-]/g, "");
}

export function resolveContactKey(value) {
  if (typeof window !== "undefined" && typeof window.canonicalPeerId === "function") {
    return window.canonicalPeerId(value);
  }
  const slug = slugPeerId(value);
  if (!slug) return "";
  return PEER_ALIASES[slug] || slug;
}

function hashString(value) {
  let hash = 0;
  for (let i = 0; i < value.length; i += 1) {
    hash = (hash << 5) - hash + value.charCodeAt(i);
    hash |= 0;
  }
  return Math.abs(hash);
}

