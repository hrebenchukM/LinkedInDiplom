function normalizeLang(value) {
  return SUPPORTED_LANGS.includes(value) ? value : FALLBACK_LANG;
}

function ThemeLanguageBootstrap({ children }) {
  const [theme, setTheme] = useState(() => {
    const rootTheme = document.documentElement.dataset.theme === "dark" ? "dark" : "light";
    try {
      const saved = window.localStorage.getItem(THEME_STORAGE_KEY) || window.localStorage.getItem("appTheme");
      return saved === "dark" || saved === "light" ? saved : rootTheme;
    } catch {
      return rootTheme;
    }
  });
  const [lang, setLang] = useState(() => {
    try {
      return normalizeLang(window.localStorage.getItem(LANG_STORAGE_KEY) || window.localStorage.getItem(APP_LANG_STORAGE_KEY) || FALLBACK_LANG);
    } catch {
      return FALLBACK_LANG;
    }
  });

  useEffect(() => {
    const nextTheme = theme === "dark" ? "dark" : "light";
    const useLight = nextTheme === "dark";
    document.documentElement.setAttribute("data-theme", nextTheme);
    document.documentElement.style.colorScheme = nextTheme;
    try {
      window.localStorage.setItem(THEME_STORAGE_KEY, nextTheme);
      window.localStorage.setItem("appTheme", nextTheme);
    } catch {
      // Ignore storage access errors in restricted modes.
    }
    document.querySelectorAll("[data-theme-toggle]").forEach((button) => {
      button.setAttribute("aria-pressed", nextTheme === "dark" ? "true" : "false");
      button.setAttribute("aria-label", useLight ? "Switch to light theme" : "Switch to dark theme");
      button.setAttribute("title", useLight ? "Light theme" : "Dark theme");
    });
  }, [theme]);

  useEffect(() => {
    const nextLang = normalizeLang(lang);
    document.documentElement.setAttribute("lang", nextLang);
    window.localStorage.setItem(APP_LANG_STORAGE_KEY, nextLang);
    window.localStorage.setItem(LANG_STORAGE_KEY, nextLang);
    window.getUiLang = () => nextLang;
    window.uiT = (key, fallback) => {
      const pack = DICT[nextLang] || DICT[FALLBACK_LANG];
      return pack?.[key] ?? fallback ?? key;
    };
    window.uiTForLang = (key, targetLang) => {
      const safe = normalizeLang(targetLang);
      const pack = DICT[safe] || DICT[FALLBACK_LANG];
      return pack?.[key] ?? key;
    };
    window.uiTmpl = (key, vars = {}, fallback) => {
      let out = window.uiT(key, fallback ?? key);
      Object.keys(vars).forEach((name) => {
        out = out.replaceAll(`{{${name}}}`, String(vars[name]));
      });
      return out;
    };
  }, [lang]);

  useEffect(() => {
    window.lockBodyScroll = () => {
      if (document.body.dataset.uiScrollLocked === "1") return;
      const scrollY = window.scrollY;
      document.body.dataset.uiScrollLocked = "1";
      document.body.dataset.uiScrollY = String(scrollY);
      document.body.style.position = "fixed";
      document.body.style.top = `-${scrollY}px`;
      document.body.style.left = "0";
      document.body.style.right = "0";
      document.body.style.width = "100%";
      document.body.style.overflow = "hidden";
    };

    window.unlockBodyScroll = () => {
      if (document.body.dataset.uiScrollLocked !== "1") return;
      const scrollY = Number(document.body.dataset.uiScrollY || 0) || 0;
      document.body.style.position = "";
      document.body.style.top = "";
      document.body.style.left = "";
      document.body.style.right = "";
      document.body.style.width = "";
      document.body.style.overflow = "";
      delete document.body.dataset.uiScrollLocked;
      delete document.body.dataset.uiScrollY;
      window.scrollTo(0, scrollY);
    };

    return () => {
      delete window.lockBodyScroll;
      delete window.unlockBodyScroll;
    };
  }, []);

  useEffect(() => {
    window.MESSAGING_CONTACTS = MESSAGING_CONTACTS;
    return () => {
      delete window.MESSAGING_CONTACTS;
    };
  }, []);

  useEffect(() => {
    const HOME_CHATS_KEY = "homeChats";
    const REMOVED_PEERS_KEY = "chatRemovedPeers";
    const ARCHIVED_PEERS_KEY = "chatArchivedPeers";
    const CONNECTED_PEERS_KEY = "networkConnectedPeers";
    const PEER_ALIASES = {
      abramlipshutz: "abram",
      marcusdias: "marcus",
      alenacurtis: "alena",
    };

    const tr = (key, fallback) => (typeof window.uiT === "function" ? window.uiT(key, fallback) : fallback || key);

    const slugPeerId = (value) =>
      String(value || "")
        .trim()
        .toLowerCase()
        .replace(/^@+/, "")
        .replace(/\s+/g, "-")
        .replace(/[^a-z0-9-]/g, "");

    const canonicalPeerId = (value) => {
      const slug = slugPeerId(value);
      if (!slug) return "";
      return PEER_ALIASES[slug] || slug;
    };

    const loadHomeChats = () => {
      try {
        const raw = localStorage.getItem(HOME_CHATS_KEY);
        if (!raw) return [];
        const data = JSON.parse(raw);
        if (!Array.isArray(data)) return [];
        const seen = new Set();
        const normalized = [];
        data.forEach((chat) => {
          const id = canonicalPeerId(chat && chat.id);
          if (!id || seen.has(id)) return;
          seen.add(id);
          normalized.push({ ...chat, id });
        });
        return normalized;
      } catch {
        return [];
      }
    };

    const saveHomeChats = (chats) => {
      try {
        localStorage.setItem(HOME_CHATS_KEY, JSON.stringify(chats));
      } catch {
        // ignore
      }
    };

    const readConnectedSet = () => {
      try {
        const raw = localStorage.getItem(CONNECTED_PEERS_KEY);
        const arr = raw ? JSON.parse(raw) : [];
        return new Set(Array.isArray(arr) ? arr.map(canonicalPeerId).filter(Boolean) : []);
      } catch {
        return new Set();
      }
    };

    const writeConnectedSet = (set) => {
      try {
        localStorage.setItem(CONNECTED_PEERS_KEY, JSON.stringify([...set].filter(Boolean)));
      } catch {
        // ignore
      }
    };

    const clearArchivedPeer = (id) => {
      const slug = canonicalPeerId(id);
      if (!slug) return;
      try {
        const raw = localStorage.getItem(ARCHIVED_PEERS_KEY);
        const arr = raw ? JSON.parse(raw) : [];
        if (!Array.isArray(arr)) return;
        const next = arr.map((x) => canonicalPeerId(x)).filter((x) => x && x !== slug);
        localStorage.setItem(ARCHIVED_PEERS_KEY, JSON.stringify(next));
      } catch {
        // ignore
      }
    };

    const clearRemovedPeer = (id) => {
      const slug = canonicalPeerId(id);
      if (!slug) return;
      try {
        const raw = localStorage.getItem(REMOVED_PEERS_KEY);
        const arr = raw ? JSON.parse(raw) : [];
        if (!Array.isArray(arr)) return;
        const next = arr.map((x) => canonicalPeerId(x)).filter((x) => x && x !== slug);
        localStorage.setItem(REMOVED_PEERS_KEY, JSON.stringify(next));
      } catch {
        // ignore
      }
    };

    const reconcileConnectedPeerState = (id) => {
      clearRemovedPeer(id);
      clearArchivedPeer(id);
    };

    const reconcileAllConnectedPeerState = () => {
      loadHomeChats().forEach((chat) => reconcileConnectedPeerState(chat && chat.id));
      readConnectedSet().forEach((slug) => reconcileConnectedPeerState(slug));
    };

    const registerMessagingContact = (entry) => {
      const slug = canonicalPeerId(entry && entry.id);
      if (!slug) return slug;
      if (!window.MESSAGING_CONTACTS || typeof window.MESSAGING_CONTACTS !== "object") {
        window.MESSAGING_CONTACTS = {};
      }
      const existing = window.MESSAGING_CONTACTS[slug] || {};
      window.MESSAGING_CONTACTS[slug] = {
        name: String((entry && entry.name) || existing.name || slug).trim(),
        seed: String((entry && entry.seed) || existing.seed || entry?.name || slug).trim(),
        avatar: String((entry && entry.avatar) || existing.avatar || "").trim(),
        phone: existing.phone || entry?.phone || "",
        email: existing.email || entry?.email || "",
        web: existing.web || entry?.web || "",
        previewKey: "",
        timeKey: "",
      };
      return slug;
    };

    const notifyMessagingUpdated = () => {
      document.dispatchEvent(new CustomEvent("homechatsupdated"));
      if (typeof window.renderMessagesWidget === "function") window.renderMessagesWidget();
      if (typeof window.renderMessagesPanel === "function") window.renderMessagesPanel();
    };

    const connectPerson = (entry) => {
      const slug = registerMessagingContact(entry);
      if (!slug) return "";
      const name = String((entry && entry.name) || slug).trim() || slug;
      const preview = String((entry && entry.preview) || tr("network.newChatPreview", "Start the conversation...")).trim();
      const time = String((entry && entry.time) || tr("js.chatNow", "Now")).trim();
      const avatar = String((entry && entry.avatar) || "").trim();
      const seed = String((entry && entry.seed) || name).trim();
      const chats = loadHomeChats().filter((c) => canonicalPeerId(c.id) !== slug);
      chats.unshift({ id: slug, name, preview, time, avatar, seed });
      saveHomeChats(chats);
      const connected = readConnectedSet();
      connected.add(slug);
      writeConnectedSet(connected);
      reconcileConnectedPeerState(slug);
      notifyMessagingUpdated();
      return slug;
    };

    const disconnectPerson = (id) => {
      const slug = canonicalPeerId(id);
      if (!slug) return false;
      const chats = loadHomeChats().filter((c) => canonicalPeerId(c.id) !== slug);
      saveHomeChats(chats);
      const connected = readConnectedSet();
      connected.delete(slug);
      writeConnectedSet(connected);
      notifyMessagingUpdated();
      return true;
    };

    const isPersonConnected = (id) => {
      const slug = canonicalPeerId(id);
      if (!slug) return false;
      try {
        const removedRaw = localStorage.getItem(REMOVED_PEERS_KEY);
        const removedArr = removedRaw ? JSON.parse(removedRaw) : [];
        if (Array.isArray(removedArr) && removedArr.some((x) => canonicalPeerId(x) === slug)) return false;
      } catch {
        // ignore
      }
      if (loadHomeChats().some((c) => canonicalPeerId(c.id) === slug)) return true;
      return readConnectedSet().has(slug);
    };

    const chatUrl = (peer) =>
      `/chat?with=${encodeURIComponent(canonicalPeerId(peer) || "marcus")}`;

    window.PEER_ALIASES = PEER_ALIASES;
    window.slugPeerId = slugPeerId;
    window.canonicalPeerId = canonicalPeerId;
    window.loadHomeChats = loadHomeChats;
    window.connectPerson = connectPerson;
    window.disconnectPerson = disconnectPerson;
    window.isPersonConnected = isPersonConnected;
    window.messagingChatUrl = chatUrl;
    window.reconcileAllConnectedPeerState = reconcileAllConnectedPeerState;

    return () => {
      delete window.PEER_ALIASES;
      delete window.slugPeerId;
      delete window.canonicalPeerId;
      delete window.loadHomeChats;
      delete window.connectPerson;
      delete window.disconnectPerson;
      delete window.isPersonConnected;
      delete window.messagingChatUrl;
      delete window.reconcileAllConnectedPeerState;
    };
  }, []);

  const value = useMemo(
    () => ({
      theme,
      lang,
      supportedLangs: SUPPORTED_LANGS,
      t: (key, fallback) => {
        const pack = DICT[normalizeLang(lang)] || DICT[FALLBACK_LANG];
        return pack?.[key] ?? fallback ?? key;
      },
      toggleTheme: () => setTheme((prev) => (prev === "dark" ? "light" : "dark")),
      toggleLang: () =>
        setLang((prev) => {
          const currentIndex = SUPPORTED_LANGS.indexOf(normalizeLang(prev));
          const nextIndex = (currentIndex + 1) % SUPPORTED_LANGS.length;
          return SUPPORTED_LANGS[nextIndex];
        }),
      setTheme: (nextTheme) => setTheme(nextTheme === "dark" ? "dark" : "light"),
      setLang: (nextLang) => setLang(normalizeLang(nextLang)),
    }),
    [theme, lang],
  );

  return <UiSettingsContext.Provider value={value}>{children}</UiSettingsContext.Provider>;
}

export function AppProviders({ children }) {
  return (
    <ThemeLanguageBootstrap>
      <AuthProvider>
        <ApiFeedbackBanner />
        <ProfileProvider>
          <NetworkProvider>
            <ChatProvider>{children}</ChatProvider>
          </NetworkProvider>
        </ProfileProvider>
      </AuthProvider>
    </ThemeLanguageBootstrap>
  );
}

export function useUiSettings() {
  const ctx = useContext(UiSettingsContext);
  if (!ctx) throw new Error("useUiSettings must be used inside AppProviders");
  return ctx;
}
